// Generates migrations/dimensions_sync.sql from "Dimension Store.csv" and "Dimension Model.csv".
// Usage: npm run dims:build   (then npm run dims:push to apply to remote D1)
// Rows missing from the CSVs are deactivated (is_active = 0), never deleted, so submissions keep their FKs.
import { readFileSync, writeFileSync } from "node:fs";

function parseCsv(text) {
  const rows = [];
  let row = [], cell = "", q = false;
  text = text.replace(/^﻿/, "");
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.some((v) => v.trim() !== "")) rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

const sql = (v) => `'${String(v).replace(/'/g, "''")}'`;
const active = (v) => (v.toLowerCase() === "active" ? 1 : 0);

const stores = parseCsv(readFileSync("Dimension Store.csv", "utf8"));
const models = parseCsv(readFileSync("Dimension Model.csv", "utf8"));

const out = [
  "-- GENERATED by scripts/sync-dimensions.mjs - do not edit by hand.",
  "UPDATE dimension_store SET is_active = 0;",
  "UPDATE dimension_model SET is_active = 0;",
];
for (const s of stores) {
  out.push(
    `INSERT OR REPLACE INTO dimension_store (store_id, store_name, store_name_th, customer_name, store_id_customer, province_th, region_th, is_active) VALUES (${[
      s.STORE_ID, s.STORE_NAME, s["Store Name TH"], s.Customer, s["Store ID Customer"], s["Province TH"], s["Region TH"],
    ].map(sql).join(", ")}, ${active(s["Active-Inactive"])});`
  );
}
for (const m of models) {
  out.push(
    `INSERT OR REPLACE INTO dimension_model (model_code, brand, category, sub_category, is_active, remark, update_by) VALUES (${[
      m.Model, m.Brand, m.Category, m.SubCategory,
    ].map(sql).join(", ")}, ${active(m["Active-Inactive"])}, ${sql(m.Remark)}, ${sql(m["Update by"] || "admin")});`
  );
}
writeFileSync("migrations/dimensions_sync.sql", out.join("\n") + "\n");
console.log(`Wrote migrations/dimensions_sync.sql: ${stores.length} stores, ${models.length} models`);
